"""
Create Version10 from frozen Version9 — lean accuracy-development fork.

Copies engineering code + input data. Excludes regenerated outputs / web_runs.
Also writes Version9/VERSION_FREEZE.md when --freeze-v9 is set (default).
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V9 = ROOT / "Version9"
V10 = ROOT / "Version10"

# Top-level trees / files relative to Version9
COPY_TREES = (
    "src",
    "Run_PY",
    "config",
    "schemas",
    "prompts",
)

COPY_FILES = (
    "requirements.txt",
    ".gitignore",
    "PIPELINE.md",
)

# data/ inputs only (not output / web_runs)
DATA_TREES = (
    "data/Benchmark_Set_2",
    "data/Benchmark_Set_3",
    "data/Excel_Presentation_Format",
    "data/framing",
    "data/general_notes",
)

WEBAPP_KEEP = (
    "app.py",
    "config.py",
    "routes.py",
    "requirements.txt",
    "README.md",
    ".gitignore",
    "services",
    "static",
    "templates",
)

IGNORE = shutil.ignore_patterns(
    "__pycache__",
    "*.pyc",
    "*.pyo",
    ".pytest_cache",
    "*.log",
    ".DS_Store",
    "Thumbs.db",
)


def _copy_tree(rel: str) -> None:
    src = V9 / rel
    dst = V10 / rel
    if not src.exists():
        print(f"  SKIP missing: {rel}")
        return
    if dst.exists():
        shutil.rmtree(dst)
    print(f"  copy tree {rel}")
    shutil.copytree(src, dst, ignore=IGNORE)


def _copy_file(rel: str) -> None:
    src = V9 / rel
    dst = V10 / rel
    if not src.exists():
        print(f"  SKIP missing: {rel}")
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    print(f"  copy file {rel}")
    shutil.copy2(src, dst)


def _copy_webapp() -> None:
    src_root = V9 / "webapp"
    dst_root = V10 / "webapp"
    if dst_root.exists():
        shutil.rmtree(dst_root)
    dst_root.mkdir(parents=True)
    for name in WEBAPP_KEEP:
        src = src_root / name
        if not src.exists():
            print(f"  SKIP webapp/{name}")
            continue
        dst = dst_root / name
        if src.is_dir():
            print(f"  copy tree webapp/{name}")
            shutil.copytree(src, dst, ignore=IGNORE)
        else:
            print(f"  copy file webapp/{name}")
            shutil.copy2(src, dst)
    for sub in ("logs", "uploads", "outputs"):
        (dst_root / sub).mkdir(parents=True, exist_ok=True)
        (dst_root / sub / ".gitkeep").write_text("", encoding="utf-8")


def _ensure_empty_data_slots() -> None:
    for rel in (
        "data/output",
        "data/web_runs",
        "data/vision_dataset",
    ):
        d = V10 / rel
        d.mkdir(parents=True, exist_ok=True)
        (d / ".gitkeep").write_text("", encoding="utf-8")
        print(f"  empty slot {rel}/")


