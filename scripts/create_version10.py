def patch_v9_readme() -> None:
    readme = V9 / "README.md"
    if not readme.exists():
        return
    banner = (
        "> **FROZEN.** Do **not** add features here. Continue work in "
        "**`Version10/`**. See `VERSION_FREEZE.md`.\n\n"
    )
    text = readme.read_text(encoding="utf-8")
    if "FROZEN" in text[:400] and "Version10" in text[:400]:
        print("  Version9/README.md already marked frozen")
        return
    # Replace active-development lead
    text = text.replace(
        "**Active development branch.** Forked from frozen **Version 8** (`v8.9.5`).",
        "**FROZEN.** Successor is **Version10**. Originally forked from frozen **Version 8** (`v8.9.5`).",
    )
    if not text.startswith(">"):
        text = banner + text
    readme.write_text(text, encoding="utf-8")
    print("  patched Version9/README.md")


def patch_v10_pipeline() -> None:
    path = V10 / "PIPELINE.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    text = text.replace("Version9", "Version10")
    path.write_text(text, encoding="utf-8")
    print("  patched Version10/PIPELINE.md (Version9 -> Version10)")


def patch_sbe_readme() -> None:
    path = ROOT / "Steel-Beam-Estimation" / "README.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    old = "| **Version9** | Accuracy: reinforcement ID & interpretation | **Active** |"
    new = (
        "| **Version9** | Accuracy through QA.2B.2 (9.6.2) | **Frozen** |\n"
        "| **Version10** | Continued accuracy / ownership / pipeline work | **Active** |"
    )
    if "| **Version10** |" in text:
        print("  Steel-Beam-Estimation/README.md already has Version10")
        return
    if old in text:
        text = text.replace(old, new)
        path.write_text(text, encoding="utf-8")
        print("  patched Steel-Beam-Estimation/README.md")
    else:
        print("  WARN: Version9 active row not found in Steel-Beam-Estimation/README.md")


def patch_v8_freeze_note() -> None:
    """Leave V8 freeze pointing at V9 historically; add note about V10."""
    path = V8 = ROOT / "Version8" / "VERSION_FREEZE.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    note = (
        "\n## Later successor\n\n"
        "Accuracy work moved from Version9 to **Version10** (2026-08-06). "
        "Version8 remains the certified production baseline; Version9 remains "
        "the completed 9.x accuracy branch.\n"
    )
    if "Version10" in text:
        print("  Version8/VERSION_FREEZE.md already mentions Version10")
        return
    path.write_text(text.rstrip() + "\n" + note, encoding="utf-8")
    print("  annotated Version8/VERSION_FREEZE.md")


def main() -> int:
    ap = argparse.ArgumentParser(description="Create Version10 from Version9")
    ap.add_argument(
        "--no-freeze-v9",
        action="store_true",
        help="Do not write Version9 freeze markers",
    )
    ap.add_argument(
        "--force",
        action="store_true",
        help="Replace an existing Version10 directory",
    )
    args = ap.parse_args()

    if not V9.exists():
        raise SystemExit(f"Version9 not found: {V9}")

    if V10.exists():
        if not args.force:
            raise SystemExit(
                f"Version10 already exists: {V10}\nRe-run with --force to replace."
            )
        print(f"Removing existing {V10} ...")
        shutil.rmtree(V10)

    print(f"Creating {V10} from {V9} ...")
    V10.mkdir(parents=True)

    for rel in COPY_TREES:
        _copy_tree(rel)
    for rel in COPY_FILES:
        _copy_file(rel)
    for rel in DATA_TREES:
        _copy_tree(rel)
    _copy_webapp()
    _ensure_empty_data_slots()
    write_v10_readme()
    patch_v10_pipeline()

    if not args.no_freeze_v9:
        write_v9_freeze()
        patch_v9_readme()
        patch_sbe_readme()
        patch_v8_freeze_note()

    print("\nDone.")
    print(f"  Active tree : {V10}")
    print(f"  Frozen tree : {V9}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
