"""
Phase V.A.2 -- benchmark2_workbook_validator.py
Validate the Estimation_Output.xlsx generated by the Version8 pipeline.
MODEL_VERSION: 7.0.0
"""
from __future__ import annotations

import pathlib
from typing import List, Optional

from benchmark2_models import WorkbookValidation, WorksheetValidation

_ROOT           = pathlib.Path(__file__).resolve().parents[3]
_V7             = _ROOT / "Version8"
_PRODUCTION_OUT = _V7 / "data/output/Production_Output"
_WORKBOOK       = _PRODUCTION_OUT / "Estimation_Output.xlsx"

_EXPECTED_SHEETS = {
    "Bar Bending Schedule",
    "Engineering Summary",
    "Steel Summary",
    "Stirrup Schedule",
}
_ENGINEERING_SHEET = "Bar Bending Schedule"


class Benchmark2WorkbookValidator:
    """Validate the generated Estimation_Output.xlsx for Benchmark Set 2."""

    def __init__(self, workbook_path: Optional[pathlib.Path] = None) -> None:
        self._path = workbook_path or _WORKBOOK

    def validate(self) -> WorkbookValidation:
        issues: List[str] = []

        if not self._path.exists():
            return WorkbookValidation(
                workbook_path=str(self._path),
                exists=False,
                readable=False,
                corrupted=False,
                size_bytes=0,
                size_kb=0.0,
                sheet_names=[],
                total_sheets=0,
                total_rows=0,
                total_columns=0,
                has_data=False,
                validation_passed=False,
                issues=["Workbook not found at expected path"],
            )

        size_bytes = self._path.stat().st_size
        size_kb    = round(size_bytes / 1024, 1)

        try:
            import openpyxl  # type: ignore
            wb = openpyxl.load_workbook(str(self._path), data_only=True)
            readable = True
        except Exception as exc:
            return WorkbookValidation(
                workbook_path=str(self._path),
                exists=True,
                readable=False,
                corrupted=True,
                size_bytes=size_bytes,
                size_kb=size_kb,
                sheet_names=[],
                total_sheets=0,
                total_rows=0,
                total_columns=0,
                has_data=False,
                validation_passed=False,
                issues=[f"Workbook corrupted or unreadable: {exc}"],
            )

        sheet_names = wb.sheetnames
        ws_validations: List[WorksheetValidation] = []
        total_rows = 0
        total_cols = 0

        for sname in sheet_names:
            ws       = wb[sname]
            rows     = ws.max_row or 0
            cols     = ws.max_column or 0
            total_rows += rows
            total_cols = max(total_cols, cols)
            has_hdr  = rows >= 1
            has_data = rows >= 2
            ws_issues: List[str] = []
            if rows == 0:
                ws_issues.append(f"Sheet '{sname}' is empty")
            ws_validations.append(
                WorksheetValidation(
                    sheet_name=sname,
                    row_count=rows,
                    col_count=cols,
                    has_headers=has_hdr,
                    has_data_rows=has_data,
                    validation_passed=has_data,
                    issues=ws_issues,
                )
            )

        missing_sheets = _EXPECTED_SHEETS - set(sheet_names)
        if missing_sheets:
            issues.append(f"Expected sheets missing: {sorted(missing_sheets)}")

        has_data = total_rows > len(sheet_names)
        if not has_data:
            issues.append("Workbook appears empty -- all sheets have only header rows or no rows")

        validation_passed = readable and not issues

        return WorkbookValidation(
            workbook_path=str(self._path),
            exists=True,
            readable=readable,
            corrupted=False,
            size_bytes=size_bytes,
            size_kb=size_kb,
            sheet_names=sheet_names,
            total_sheets=len(sheet_names),
            total_rows=total_rows,
            total_columns=total_cols,
            has_data=has_data,
            validation_passed=validation_passed,
            worksheet_validations=ws_validations,
            issues=issues,
        )
